# 題目：(可變視窗)
    # 給你一個正整數陣列 nums 和一個目標值 target,
    # 要求找出「和 ≥ target」的最短連續子陣列長度,如果不存在就回傳 0。
        # Input: target = 7, nums = [2,3,1,2,4,3]
        # Output: 2
        # Explanation: The subarray [4,3] has the minimal length under the problem constraint.

# 想法：
    # 為什麼這題會讓你聯想到滑動窗口?
        # 想像你在追一齣連續劇
        # 假設你要找「連續看幾集,内容份量(和)至少要達到某個標準」的最短區間。如果劇集是連續的(第3集接第4集接第5集),你會怎麼「找」這個區間?
        # 你不會東挑一集、西挑一集(像 subsequence 那樣跳著選),而是:
            # 從某一集開始(左邊界),
            # 一路往後續看(右邊界往右移),
            # 邊看邊累加「份量」,
            # 一旦累加到「達標」,就可以回頭看看能不能把左邊界往右收一點,讓區間變短、但份量還是達標。
        # 因為子陣列規定「連續」,所以你只需要維護「左邊界」和「右邊界」這兩個指標,
        # 窗口內的元素永遠是原陣列中連續的一段——你不需要、也不能跳著選元素。

    # 窗口的大小(長度)在這一題裡是要由程式動態決定，窗口長度本身就是我們要找的答案。
    # 收縮條件：當window(總和) >= target 就要將left往右移
        # 已經達標之後，要去記錄起來目前subarray的長度，收縮後在去尋找下一個達標得是否有 < subarray長度
        # 但如果把「記錄長度」的動作放在 while 迴圈外面，會等到不合法，也就是小於target後才跳出迴圈紀錄長度
        # 但此時的subarray長度的答案，必定不是我們要的最小，會抓不到達標當下的長度，會收縮並錯過
        # 所以記錄這件事要放在while，當合法就去紀錄
        # 順序是，先記錄，在收縮，因為收縮後的長度一定會比達標時的長度小，所以要先記錄達標時的長度，再去收縮。